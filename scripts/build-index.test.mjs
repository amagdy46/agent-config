// Run: node --test
// Each case builds a throwaway repository and runs the generator against it.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, test } from "node:test";
import { fileURLToPath } from "node:url";

const script = join(dirname(fileURLToPath(import.meta.url)), "build-index.mjs");
const temp = mkdtempSync(join(tmpdir(), "build-index-"));
after(() => rmSync(temp, { recursive: true, force: true }));

const START = "<!-- skills-table:start (generated by scripts/build-index.mjs from FAILURES.md; do not edit) -->";
const README = `# Demo\n\nIntro stays.\n\n${START}\nold table\n<!-- skills-table:end -->\n\nold line <!-- startup-cost -->\n\n## After\n\nOutro stays.\n`;
const section = (name, stage, forYou = `use ${name}.`) =>
  `## ${name}\n\nStage: ${stage}\nFor you: ${forYou}\nFixes: It broke.\nOrigin: inherited\n\nWhy.\n\n`;

let count = 0;
// Two skills; FAILURES.md lists the Build one first, so stage order must win.
function repo({ failures, summary } = {}) {
  const root = join(temp, String(count++));
  for (const [name, description] of [["alpha", "Do alpha."], ["beta", "Do beta | gamma."]]) {
    mkdirSync(join(root, "skills", name), { recursive: true });
    writeFileSync(join(root, "skills", name, "SKILL.md"), `---\nname: ${name}\ndescription: ${description}\n---\n\nBody.\n`);
  }
  writeFileSync(join(root, "FAILURES.md"), failures ?? `# Failure log\n\n${section("alpha", "Build")}${section("beta", "Think", "split a | b.")}`);
  writeFileSync(join(root, "README.md"), README);
  if (summary) {
    mkdirSync(join(root, "evals"));
    writeFileSync(join(root, "evals", "summary.json"), JSON.stringify(summary));
  }
  return root;
}

const build = (root, ...flags) => spawnSync(process.execPath, [script, ...flags, root], { encoding: "utf8" });
const read = (root, file) => readFileSync(join(root, file), "utf8");

test("writes skills.json and the README regions, and nothing else", () => {
  const root = repo();
  const result = build(root);
  assert.equal(result.status, 0, result.stderr);
  const index = JSON.parse(read(root, "skills.json"));
  assert.deepEqual(index.skills.map((skill) => skill.name), ["beta", "alpha"]);
  // "alpha" + "Do alpha." = 14 bytes; "beta" + "Do beta | gamma." = 20 bytes.
  assert.deepEqual(index.startup, { bytes: 34, approxTokens: 9 });
  assert.equal(index.count, 2);
  assert.equal(index.evals, null);
  assert.deepEqual(index.skills[1], {
    name: "alpha",
    path: "skills/alpha/SKILL.md",
    description: "Do alpha.",
    stage: "Build",
    forYou: "use alpha.",
    fixes: "It broke.",
    origin: "inherited",
    bytes: 50,
    startupBytes: 14,
    eval: null,
  });
  const readme = read(root, "README.md");
  assert.equal(
    readme,
    `# Demo\n\nIntro stays.\n\n${START}\n` +
      "| Stage | Skill | For you | Startup bytes |\n| --- | --- | --- | --: |\n" +
      "| Think | [beta](skills/beta/SKILL.md) | split a \\| b | 20 |\n" +
      "| Build | [alpha](skills/alpha/SKILL.md) | use alpha | 14 |\n" +
      "<!-- skills-table:end -->\n\n" +
      "At session start an agent loads only each skill's name and description: 2 skills, 34 bytes, about 9 tokens. <!-- startup-cost -->\n\n" +
      "## After\n\nOutro stays.\n",
  );
});

test("two runs give identical bytes, and the second writes nothing", () => {
  const root = repo();
  build(root);
  const first = [read(root, "skills.json"), read(root, "README.md")];
  const again = build(root);
  assert.equal(again.stdout, "ok: nothing changed\n");
  assert.deepEqual([read(root, "skills.json"), read(root, "README.md")], first);
});

test("--check passes when current and fails in one line when a description changes", () => {
  const root = repo();
  assert.equal(build(root, "--check").status, 1, "stale before the first build");
  build(root);
  assert.equal(build(root, "--check").status, 0);
  const file = join(root, "skills", "alpha", "SKILL.md");
  writeFileSync(file, read(root, "skills/alpha/SKILL.md").replace("Do alpha.", "Do alpha now."));
  const before = [read(root, "skills.json"), read(root, "README.md")];
  const result = build(root, "--check");
  assert.equal(result.status, 1);
  assert.equal(result.stderr, "error: skills.json and README.md are not what the generator would write (a source changed, or a generated file was edited by hand). Run node scripts/build-index.mjs and commit the result.\n");
  assert.deepEqual([read(root, "skills.json"), read(root, "README.md")], before, "--check wrote a file");
});

test("a skill with no FAILURES.md section fails with a fix, and writes nothing", () => {
  const root = repo({ failures: `# Failure log\n\n${section("alpha", "Build")}` });
  const result = build(root);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /^error: FAILURES\.md: no "## beta" section for skills\/beta\/\. Add one with Stage:, For you:, Fixes: and Origin: lines/);
  assert.equal(read(root, "README.md"), README);
});

test("an eval summary adds a column; a skill missing from it shows not run", () => {
  const summary = { generated: "2026-11-18", model: "m", skills: { alpha: { cases: 3, with: 0.89, without: 0.44, delta: 0.45 } } };
  const root = repo({ summary });
  assert.equal(build(root).status, 0);
  const index = JSON.parse(read(root, "skills.json"));
  assert.deepEqual(index.evals, { generated: "2026-11-18", model: "m" });
  assert.deepEqual(index.skills[1].eval, summary.skills.alpha);
  assert.equal(index.skills[0].eval, null);
  const readme = read(root, "README.md");
  assert.match(readme, /\| Stage \| Skill \| For you \| Startup bytes \| Eval gain \|\n\| --- \| --- \| --- \| --: \| --: \|/);
  assert.match(readme, /\| \[alpha\]\(skills\/alpha\/SKILL\.md\) \| use alpha \| 14 \| \+0\.45 \(3 cases\) \|/);
  assert.match(readme, /\| \[beta\]\(skills\/beta\/SKILL\.md\) \| split a \\\| b \| 20 \| not run \|/);
});

test("missing README markers fail with where to put them", () => {
  const root = repo();
  writeFileSync(join(root, "README.md"), "# Demo\n");
  const result = build(root);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /README\.md: no skills table markers\. Put/);
  assert.match(result.stderr, /README\.md: 0 lines carry "<!-- startup-cost -->"\. Keep it at the end of exactly one line/);
});
