#!/usr/bin/env node

// Join the facts about each skill into skills.json and the README's skills
// table, so people and tools read the same numbers. Each fact has one source:
//
//   skills/<name>/SKILL.md  name, description, size in bytes
//   FAILURES.md             stage, "For you", "Fixes" and "Origin" lines
//   evals/summary.json      eval result, when the file exists
//
// Usage: node scripts/build-index.mjs [--check] [repository root]
// --check writes nothing and exits 1 when either output is stale.
//
// evals/summary.json, written by the eval runner. A missing file, or a skill
// missing from "skills", means that skill was not evaluated. "with" and
// "without" are pass rates from 0 to 1 with and without the skill loaded:
//
//   { "generated": "2026-11-18", "model": "<model the numbers are from>",
//     "skills": { "brainstorm": { "cases": 3, "with": 0.89, "without": 0.44, "delta": 0.45 } } }

import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { STAGES, frontmatterOf, parseFailures, startupBytes } from "./lib/skills.mjs";

const args = process.argv.slice(2);
const check = args.includes("--check");
const root = resolve(args.find((arg) => !arg.startsWith("--")) ?? join(dirname(fileURLToPath(import.meta.url)), ".."));
const TABLE_START = "<!-- skills-table:start (generated by scripts/build-index.mjs from FAILURES.md; do not edit) -->";
const TABLE_END = "<!-- skills-table:end -->";
const STARTUP_MARK = "<!-- startup-cost -->";

function fail(messages) {
  for (const message of messages) console.error(`error: ${message}.`);
  process.exit(1);
}

const thousands = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
const cell = (text) => text.replace(/\|/g, "\\|");

// Skills: name, description and size, from each SKILL.md.
const skills = new Map();
const problems = [];
const folders = (await readdir(join(root, "skills"), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
for (const name of folders) {
  const file = join(root, "skills", name, "SKILL.md");
  const at = `skills/${name}/SKILL.md`;
  if (!existsSync(file)) {
    problems.push(`${at}: missing. Add SKILL.md, or delete the folder`);
    continue;
  }
  const text = await readFile(file, "utf8");
  let fields;
  try {
    fields = frontmatterOf(text);
  } catch (error) {
    problems.push(`${at}: ${error.message}`);
    continue;
  }
  if (!fields) {
    problems.push(`${at}: no frontmatter. Start the file with a "---" line, the name and description fields, and a closing "---" line`);
    continue;
  }
  if (typeof fields.description !== "string" || !fields.description) {
    problems.push(`${at}: no description. Add "description:" to the frontmatter`);
    continue;
  }
  skills.set(name, { description: fields.description, bytes: Buffer.byteLength(text) });
}

// Stage and the one-line facts, from FAILURES.md.
const failuresFile = join(root, "FAILURES.md");
let sections = new Map();
if (!existsSync(failuresFile)) {
  problems.push(`FAILURES.md: not found. Add it with one "## <name>" section per skill`);
} else {
  const parsed = parseFailures(await readFile(failuresFile, "utf8"), folders);
  sections = parsed.sections;
  problems.push(...parsed.errors.map((error) => `FAILURES.md: ${error}`));
}

// Eval results, when there are any.
const summaryFile = join(root, "evals", "summary.json");
let summary = null;
if (existsSync(summaryFile)) {
  try {
    summary = JSON.parse(await readFile(summaryFile, "utf8"));
  } catch (error) {
    problems.push(`evals/summary.json: not valid JSON (${error.message}). Fix the file or rerun the evals`);
  }
  if (summary && (typeof summary.skills !== "object" || summary.skills === null)) {
    problems.push(`evals/summary.json: no "skills" object. See the format at the top of scripts/build-index.mjs`);
    summary = null;
  }
  for (const [name, result] of Object.entries(summary?.skills ?? {})) {
    const numbers = ["cases", "with", "without", "delta"].every((key) => typeof result?.[key] === "number");
    if (!numbers) problems.push(`evals/summary.json: "${name}" needs numeric cases, with, without and delta. See the format at the top of scripts/build-index.mjs`);
    else if (!folders.includes(name)) problems.push(`evals/summary.json: "${name}" is not a skill in skills/. Remove it or rerun the evals`);
  }
}

if (problems.length) fail(problems);

// README-table order: by stage, then by the order of the sections in FAILURES.md.
const order = [...sections.keys()];
const names = [...skills.keys()].sort(
  (a, b) => STAGES.indexOf(sections.get(a).stage) - STAGES.indexOf(sections.get(b).stage) || order.indexOf(a) - order.indexOf(b),
);
const entries = names.map((name) => {
  const { stage, forYou, fixes, origin } = sections.get(name);
  const { description, bytes } = skills.get(name);
  const result = summary?.skills[name];
  return {
    name,
    path: `skills/${name}/SKILL.md`,
    description,
    stage,
    forYou,
    fixes,
    origin,
    bytes,
    startupBytes: startupBytes(name, description),
    eval: result ? { cases: result.cases, with: result.with, without: result.without, delta: result.delta } : null,
  };
});
const total = entries.reduce((sum, entry) => sum + entry.startupBytes, 0);
const tokens = Math.round(total / 4);
const index = {
  count: entries.length,
  startup: { bytes: total, approxTokens: tokens },
  evals: summary ? { generated: summary.generated ?? null, model: summary.model ?? null } : null,
  skills: entries,
};
const json = JSON.stringify(index, null, 2) + "\n";

// README: the skills table and the startup-cost line.
const header = ["Stage", "Skill", "For you", "Startup bytes", ...(summary ? ["Eval gain"] : [])];
const rows = entries.map((entry, i) => {
  const stage = i === 0 || entries[i - 1].stage !== entry.stage ? entry.stage : "";
  const row = [stage, `[${entry.name}](${entry.path})`, cell(entry.forYou.replace(/\.$/, "")), String(entry.startupBytes)];
  if (summary) {
    const e = entry.eval;
    row.push(e ? `${e.delta >= 0 ? "+" : ""}${e.delta.toFixed(2)} (${e.cases} cases)` : "not run");
  }
  return row;
});
const line = (cells) => `| ${cells.join(" | ")} |`;
const table = [line(header), line(header.map((_, i) => (i >= 3 ? "--:" : "---"))), ...rows.map(line)].join("\n");
const sentence = `At session start an agent loads only each skill's name and description: ${entries.length} skills, ${thousands(total)} bytes, about ${thousands(tokens)} tokens.`;

const readmeFile = join(root, "README.md");
const readme = existsSync(readmeFile) ? await readFile(readmeFile, "utf8") : "";
const start = readme.indexOf(TABLE_START);
const end = readme.indexOf(TABLE_END);
const markerProblems = [];
if (start === -1 || end < start) {
  markerProblems.push(`README.md: no skills table markers. Put "${TABLE_START}" and "${TABLE_END}" on their own lines where the table belongs`);
}
const startupLines = readme.split("\n").filter((text) => text.includes(STARTUP_MARK)).length;
if (startupLines !== 1) {
  markerProblems.push(`README.md: ${startupLines} lines carry "${STARTUP_MARK}". Keep it at the end of exactly one line, which the script rewrites`);
}
if (markerProblems.length) fail(markerProblems);
const newReadme = (readme.slice(0, start + TABLE_START.length) + "\n" + table + "\n" + readme.slice(end))
  .split("\n")
  .map((text) => (text.includes(STARTUP_MARK) ? `${sentence} ${STARTUP_MARK}` : text))
  .join("\n");

const outputs = [
  ["skills.json", join(root, "skills.json"), json],
  ["README.md", readmeFile, newReadme],
];
const stale = [];
for (const [label, file, content] of outputs) {
  const current = existsSync(file) ? await readFile(file, "utf8") : null;
  if (current !== content) stale.push([label, file, content]);
}
if (check) {
  if (stale.length) {
    const labels = stale.map(([label]) => label).join(" and ");
    console.error(`error: ${labels} ${stale.length > 1 ? "are" : "is"} not what the generator would write (a source changed, or a generated file was edited by hand). Run node scripts/build-index.mjs and commit the result.`);
    process.exit(1);
  }
  console.log("ok");
} else {
  for (const [, file, content] of stale) await writeFile(file, content);
  console.log(stale.length ? `wrote ${stale.map(([label]) => label).join(", ")}` : "ok: nothing changed");
}
